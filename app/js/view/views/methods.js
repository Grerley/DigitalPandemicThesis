// methods.js: Screen 9, equations, parameters, scope of the claims, references and reproducibility.

import { h } from "../dom.js";
import { panel } from "../ui.js";
import { viewHead, table } from "../common.js";
import { LAB, PARAM_META, RANGES, CENTRAL } from "../../model/params.js";

export function MethodsView() {
  const el = h("div", { class: "view" });
  el.appendChild(viewHead("Screen 9 · Methods and sources", "Methods, parameters and sources", "What the lab computes, where each number comes from, and what it does not claim."));

  el.appendChild(panel({ title: "The equations", children: [
    h("div", { class: "eq", html:
      "dS/dt = ν − (λ + α) S + γ₁ A − ν S<br>dA/dt = (λ + α) S − (σ + γ₁ + ν) A + δ R<br>dI/dt = σ A − (γ₂ + ν) I<br>dR/dt = γ₂ I − (δ + ν) R,&nbsp;&nbsp; λ = b (I + η A)" }),
    h("p", { class: "prose", html: "All rates are per year. The published HBSC prevalence is identified with <var>I</var>. With <var>a</var> = σ + γ₁ + ν, <var>c</var> = γ₂ + ν and <var>d</var> = δ + ν, " +
      "R₀ = b d (η c + σ)/(a c d − σ γ₂ δ) when α = 0, and the floor as b → 0 is I*<sub>min</sub> = (σ/c)·α/(α m + ω), with m = 1 + σ/c + σγ₂/(cd) and ω = (acd − σγ₂δ)/(cd)." }),
  ] }));

  el.appendChild(panel({ title: "Parameters", children: [
    table(["Rate", "Range carried", "Central", "Basis"],
      ["eta", "alpha", "sigma", "gamma1", "gamma2", "delta", "nu"].map((k) => [`${PARAM_META[k].sym} ${PARAM_META[k].label}`,
        `${RANGES[k].low} to ${RANGES[k].high}${RANGES[k].log ? " (log scale)" : ""}`, CENTRAL.rates[k].toFixed(4), PARAM_META[k].source]),
      ["l", "r", "r", "l"]),
    h("p", { class: "prose", html: `Ranges come from published follow-up studies of internet addiction, gaming disorder and smartphone addiction, converted to annual hazards by r = −ln(1 − p)/t; none concerns problematic social media use at the HBSC cut-off, and none comes from Africa. The exposure rate is solved exactly from the HBSC figures for each draw: at the central rates b₀ = ${CENTRAL.b0.toFixed(3)} before 2018 and b₁ = ${CENTRAL.b1.toFixed(3)} after, or a shock Δα = ${CENTRAL.dAlpha.toFixed(3)} in 2020 and 2021.` }),
  ] }));

  el.appendChild(panel({ title: "Scope of the claims", children: [
    h("ul", { class: "prose" }, [
      h("li", { text: "The model describes the dynamics of a measured behaviour, problematic social media use on the Social Media Disorder Scale. It is not a diagnosis." }),
      h("li", { text: "The exposure rate bundles influence, homophily and shared environment. It is not a causal peer effect, and reproduction numbers are properties of the model." }),
      h("li", { text: "The lab makes no claim that social media causes poor mental health." }),
      h("li", { text: "Projections are consequences of stated scenarios and parameter ranges, not forecasts." }),
      h("li", { text: "Intervention effects rest on assumed efficacies and describe relative leverage inside the model. No costs are modelled." }),
      h("li", { text: "South Africa has no measure of problematic social media use among adolescents. South African results are scenarios and a research design, not estimates." }),
    ]),
  ] }));

  el.appendChild(panel({ title: "Reproducibility", children: [
    h("p", { class: "prose", html: `Thesis results shown in the lab are generated by <code>python/export_lab.py</code> from the outputs of the thesis analysis (repository <code>github.com/Grerley/DigitalPandemicThesis</code>, commit <code>${LAB.meta.commit}</code>, exported ${LAB.meta.generated}). ` +
      "Live results come from a JavaScript port of the model. The self-test (top right, and <code>node app/test/selftest.mjs</code>) checks the port against the Python values: thresholds, equilibria, the floor, the exactly solved exposure rates, trajectories under both scenarios, projection medians across all kept draws and the network transmissibility. " +
      "Network runs use graphs generated in the browser, so individual runs differ from the thesis's runs while their distributions agree." }),
    h("p", { class: "hint", text: "An earlier version of this lab, built on the first version of the thesis, is archived in the repository (archive/simulation-lab-v1, tag simulation-lab-v1) and is not consistent with the current thesis." }),
  ] }));

  el.appendChild(panel({ title: "References", children: [
    h("div", { class: "prose", style: { fontSize: "13px" } }, Object.values(LAB.references).sort().map((a) =>
      h("p", { style: { paddingLeft: "1.5em", textIndent: "-1.5em", margin: "0 0 6px" }, html: a.replace(/\*(.*?)\*/g, "<em>$1</em>") }))),
  ] }));
  return { el };
}
